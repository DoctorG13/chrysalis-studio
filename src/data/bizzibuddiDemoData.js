export function getDemoSummary(data = bizzibuddiDemoData) {
  return {
    people: data.people.length,
    openJobs: data.jobs.filter((job) => job.status !== "Complete").length,
    appointments: data.appointments.length,
    outstanding: data.invoices.reduce(
      (sum, invoice) => sum + Number(invoice.balance || 0),
      0
    ),
    productionActive: data.production.filter(
      (record) => record.stage !== "Complete"
    ).length,
  };
}
